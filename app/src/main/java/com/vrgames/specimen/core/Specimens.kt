package com.vrgames.specimen.core

/** Which drawer of the cabinet. */
enum class Group(val title: String, val hint: String) {
    BEETLE("鞘翅目·甲虫", "前翅硬得像壳，叫鞘翅，合起来盖住后翅。"),
    WINGED("鳞翅目等·有翅昆虫", "翅膀露在外面，蝴蝶和蛾的翅上长满鳞片。"),
    MINERAL("矿物", "天然长成的晶体，不是活物留下的。"),
    FOSSIL("化石", "很久以前的生命，留在石头或树脂里。"),
}

/** A thing to compare by: what a graphic on the card shows. */
sealed interface Measure {
    /** Real body or wing size, in cm, drawn beside a coin. */
    data class Size(val cm: Double, val label: String) : Measure
    /** Mohs hardness. */
    data class Hardness(val low: Double, val high: Double) : Measure
    /** First and last seen, in millions of years ago. */
    data class Age(val from: Int, val to: Int) : Measure
}

/** One specimen: everything on its card and what the narrator says. */
class Specimen(
    val id: String,
    val name: String,
    val latin: String,
    val group: Group,
    val home: String,
    val measure: Measure,
    /** Three things to look at, each a few words. */
    val look: List<String>,
    /** The one sentence to remember, with its number. */
    val wow: String,
    /** What the narrator says over it: about 20 to 30 seconds. */
    val narration: String,
    /** The clue given after a wrong guess. */
    val clue: String,
)

